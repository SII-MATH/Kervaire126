#!/usr/bin/env python3
"""Rebuild and replay all native Ceta-to-sphere quotient certificates.
Python preparation is not proof certification. Only the complete Lean target
and its final axiom/import audit can certify the fixed algebraic quotient map.
No actual spectrum-map comparison is claimed.
"""
import argparse
import fcntl
import json
from pathlib import Path
import subprocess
import sys


def find_root(package):
    return next((p for p in package.parents if (p/'lean-toolchain').is_file()
                 and (p/'docs/external-inputs.json').is_file()), None)


def run(command):
    subprocess.run([str(x) for x in command], check=True)


def main():
    package = Path(__file__).resolve().parent
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=find_root(package))
    parser.add_argument('--output-dir', type=Path, required=True)
    parser.add_argument('--prepare-only', action='store_true', help='Generate unchecked inputs and Lean sources without compiling')
    parser.add_argument('--check', action='store_true', help='Rebuild inputs and check existing generated bytes; do not compile')
    parser.add_argument('--jobs', type=int, default=2)
    parser.add_argument('--target', action='append', default=[], help='Optional generated module target; subsets never certify the full map')
    args = parser.parse_args()
    if args.root is None:
        parser.error('--root is required outside the repository')
    root, output = args.root.resolve(), args.output_dir.resolve()
    if output == package or output.is_relative_to(package):
        parser.error('use a separate output directory; generated data does not belong in the tool package')
    if args.check and not (output/'manifest.json').is_file():
        parser.error('--check requires existing generated output; first use --prepare-only')
    if not 1 <= args.jobs <= 4:
        parser.error('--jobs must be between 1 and 4')
    output.mkdir(parents=True, exist_ok=True)
    # Never regenerate source inputs under a live runner. The common runner
    # reacquires this same lock before any compilation or cache validation.
    with (output/'runner.lock').open('a') as lock:
        fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        witness = output/'witness/CetaToSphere.jsonl'
        rebuild = [sys.executable, package/'rebuild-witness.py', '--root', root, '--output', witness]
        generate = [sys.executable, package/'generate.py', '--root', root,
                    '--output-dir', output, '--witness', witness]
        if args.check:
            rebuild += ['--manifest', output/'manifest.json', '--check']
            generate += ['--check']
        run(rebuild)
        run(generate)
        manifest = json.loads((output/'manifest.json').read_text())
        if manifest.get('complete_native_quotient_map_certified') is not False or manifest.get('actual_model_comparison_certified') is not False:
            raise ValueError('Python generation must not promote mathematical certification')
        print('Prepared complete native inputs; mathematical certification remains false.', flush=True)
    if args.prepare_only or args.check:
        return
    command = [sys.executable, '-u', package/'runner.py', '--output-dir', output, '--jobs', str(args.jobs)]
    for target in args.target:
        command += ['--target', target]
    run(command)


if __name__ == '__main__':
    main()
