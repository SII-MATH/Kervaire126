#!/usr/bin/env python3
"""Reinterpret the same Words200 witnesses in the untruncated native algebra.

Rebuild the authenticated original manifest before proposing proofs. Lean uses
the original boolean certificates and original relation membership, never a
truncated-quotient equation as a premise for an untruncated equation.
"""
import argparse
import importlib.util
from pathlib import Path

import sys as _module_sys
from pathlib import Path as _ModulePath
_module_sys.path.insert(0, str(_ModulePath(__file__).resolve().parent))
from lean_module import lean_module, module_output
ROOT = Path(__file__).resolve().parents[3]
LIN = ROOT / 'KIP126/LinProgram'
DEST = LIN / 'Certificates/Naturality/Words200/Native.lean'


@module_output
def render(p):
    parts = ['''import KIP126.LinProgram.Certificates.Naturality.Words200.All
import KIP126.LinProgram.Certificates.Naturality.NativeWordCertificate

/-! Generated by generate-native-word-replay.py. All original 15951 witnesses
are checked in A using original CSV relations. No actual-map or quotient-descent
claim is added, and the old D equations are not used to infer A equations. -/
namespace KIP126.LinModule.NaturalityWords200
open KIP126.LinE2 NativeMapCertificates BatchMapCertificate
set_option maxRecDepth 100000
set_option maxHeartbeats 16000000
set_option Elab.async false
''']
    for shard in p['shards']:
        name = shard['name']
        extra_simp = ', List.forall_mem_cons' if shard['relation_indices'] else ''
        parts.append(f'''private theorem {name}_relations_mem :
    ∀ code ∈ {name}.certificate.relationCodes, code ∈ LinE2.RawData.relations := by
  change ∀ code ∈ RawData.NaturalityWords200.{name}.relationCodes, code ∈ LinE2.RawData.relations
  simp only [RawData.NaturalityWords200.{name}.relationCodes{extra_simp}]
''')
        proofs = []
        for i in shard['relation_indices']:
            ci = p['relation_records'][i]['chunk_index']
            group = 'RelationsFirst' if ci is None else f'RelationChunk{ci:03d}'
            proofs.append(f'Shared.{group}.relation{i}_mem')
        parts.append('  exact ⟨' + ', '.join(proofs) + ', by simp⟩\n' if proofs else '  simp\n')
    parts.append('''theorem batch_relations_mem :
    ∀ b ∈ batches, ∀ code ∈ b.relationCodes, code ∈ LinE2.RawData.relations := by
  simp only [batches, List.forall_mem_cons]
''')
    parts.append('  exact ⟨' + ', '.join(s['name']+'_relations_mem' for s in p['shards']) + ', by simp⟩\n')
    parts.append('''
/-- Full unchanged entry collection: the proof reuses only finite checks and
catalogue memberships, not any equation in the truncated algebra. -/
theorem entry_native_evaluate (e : Entry) (he : e ∈ entries) :
    NativeWordCertificate.evaluatePowers NativeWordCertificate.generatorImage (word e) =
      NativeWordCertificate.targetValue e := by
  obtain ⟨b, hb, he⟩ := List.mem_flatMap.mp he
  exact NativeWordCertificate.check_sound_evaluate b.relationCodes e
    ((List.all_eq_true.mp b.checks) e he) (batch_relations_mem b hb)

theorem zero_native_evaluate (e : Entry) (he : e ∈ entries) (hz : e.targets = []) :
    NativeWordCertificate.evaluatePowers NativeWordCertificate.generatorImage (word e) = 0 := by
  rw [entry_native_evaluate e he]
  simp only [NativeWordCertificate.targetValue, hz, List.map_nil, List.sum_nil]

/-- Applying the canonical quotient map gives exactly the original D equation. -/
theorem entry_truncate_compatible (e : Entry) (he : e ∈ entries) :
    Presentation.evaluatePowers NaturalityMapCertificate.generatorImage (word e) =
      BatchMapCertificate.targetValue e := by
  have h := congrArg truncate (entry_native_evaluate e he)
  simpa only [NativeWordCertificate.truncate_evaluatePowers,
    NativeWordCertificate.truncate_generatorImage,
    NativeWordCertificate.truncate_targetValue] using h

/-- Coverage remains the same entire original source-ID interval. -/
theorem native_source_ids : entries.map (fun e => e.source.id) = List.range' 2 15951 := source_ids

theorem native_entry_count : entries.length = 15951 := entry_count
end KIP126.LinModule.NaturalityWords200
''')
    return ''.join(parts)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    spec = importlib.util.spec_from_file_location('native_words', LIN/'Translate/replay-naturality-words.py')
    words = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(words)
    p = words.rebuild()
    words.batch.validate_candidate(words.batch.load_json((LIN/'Generated/Naturality/Words200/Manifest.json').read_text()), p)
    body = render(p)
    if args.check:
        words.require(DEST.is_file() and DEST.read_text() == body, 'native word replay proof differs')
    else:
        DEST.write_text(body)
    print('checked' if args.check else 'generated', len(p['entries']), 'native word reinterpretations')


if __name__ == '__main__':
    main()
