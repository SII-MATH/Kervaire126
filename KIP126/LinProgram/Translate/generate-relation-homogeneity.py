#!/usr/bin/env python3
"""Propose kernel certificates for all 231848 original CSV relations.

Original raw payloads and archived row order are authenticated first. The
Python degree calculation is diagnostic: each emitted Lean proof independently
checks the archived characters and uses the generic parser-soundness theorem.
"""
import argparse
import csv
import importlib.util
import io
import json
import re
from pathlib import Path

import sys as _module_sys
from pathlib import Path as _ModulePath
_module_sys.path.insert(0, str(_ModulePath(__file__).resolve().parent))
from lean_module import lean_module, module_output

ROOT = Path(__file__).resolve().parents[3]
LIN = ROOT / 'KIP126/LinProgram'
BASE = 'KIP126.LinProgram.Certificates.RelationCatalogue'
COUNT = 231848


def validate_relations(degrees, relations):
    def require(condition, message):
        if not condition:
            raise ValueError(message)
    for index, code in enumerate(relations):
        ds = []
        for m in code.split(';'):
            ns = list(map(int, m.split(','))) if m else []
            require(len(ns) % 2 == 0, f'odd exponent vector at row {index}')
            require(all(a >= 0 for a in ns[1::2]), f'negative exponent at row {index}')
            require(all(0 <= i < len(degrees) for i in ns[::2]), f'generator index at row {index}')
            ds.append(tuple(sum(a * degrees[i][j] for i, a in zip(ns[::2], ns[1::2])) for j in (0, 1)))
        require(len(set(ds)) == 1, f'inhomogeneous CSV relation at row {index}')


def authenticate():
    spec = importlib.util.spec_from_file_location('homogeneity_batch', LIN / 'Translate/replay-naturality-batch.py')
    batch = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(batch)
    _, manifest_bytes, _ = batch.authenticated('KIP126/LinProgram/Raw/manifest.json')
    manifest = batch.load_json(manifest_bytes.decode())
    records = {r['path']: r for r in manifest['files']}
    native = batch.load('native-contract.py', 'homogeneity_native')
    low = native.load_lowstem()
    rows = {}
    for name in ('S0_AdamsE2_generators.csv', 'S0_AdamsE2_relations.csv'):
        _, data, digest = low.pinned(name)
        batch.require(digest == records[name]['sha256'] and len(data) == records[name]['size'],
                      'original CSV hash/size mismatch: ' + name)
        rows[name] = list(csv.DictReader(io.StringIO(data.decode('utf-16'))))
    generators = rows['S0_AdamsE2_generators.csv']
    degrees = [(int(r['s']), int(r['s']) + int(r['stem'])) for r in generators]
    relations = [r['rel'] for r in rows['S0_AdamsE2_relations.csv']]
    batch.require(len(degrees) == 2914 and len(relations) == COUNT, 'fixed catalogue count drift')
    validate_relations(degrees, relations)
    archived = (LIN / 'Generated/E2.lean').read_text()
    first = archived.split('def firstRelations : List String := ', 1)[1].split('\n', 1)[0]
    chunk_source = archived.split('def relationChunks : Array String := #[', 1)[1].split('\n]', 1)[0]
    chunks = [json.loads(s) for s in re.findall(r'"(?:[^"\\]|\\.)*"', chunk_source)]
    fixed = json.loads(first) + [r for s in chunks for r in s.split('\n')]
    batch.require(fixed == relations, 'archived relation strings/order disagree with original CSV')
    return len(chunks)


@module_output
def render(count):
    out = {}
    directory = LIN / 'Certificates/RelationCatalogue'
    for i in range(count):
        name = f'Chunk{i:03d}'
        out[directory / (name + '.lean')] = f'''import {BASE}.Automation
import all Init.Data.List.SplitOn.Basic

/-! Generated by generate-relation-homogeneity.py; original chunk {i}.
The computation is certified by the Lean kernel, without native_decide. -/
namespace KIP126.LinE2.RelationCatalogue
set_option maxRecDepth 100000
set_option maxHeartbeats 8000000
set_option cbv.maxSteps 10000000
set_option Elab.async false
open Lean Elab Tactic in
private noncomputable def chars : List Char := by
  run_tac
    (← getMainGoal).assign (toExpr (RawData.relationChunks[{i}]!).toList)
    replaceMainGoal []
private theorem checked : charsChunkCheck chars = true := by decide +kernel

theorem chunk{i:03d}_check :
    chunksCheck ((RawData.relationChunks.toList.drop {i}).take 1) = true := by
  lin_homogeneous_chunk chars checked
end KIP126.LinE2.RelationCatalogue
'''
    imports = ''.join(f'import {BASE}.Chunk{i:03d}\n' for i in range(count))
    names = ' '.join(f'chunk{i:03d}_check' for i in range(count))
    out[directory / 'Homogeneity.lean'] = imports + f'''
/-! All {COUNT} original CSV polynomials are weighted homogeneous.
This is syntactic polynomial homogeneity, not correctness of the relations
in the actual Adams E₂. The first three rows and every archived chunk occur. -/
namespace KIP126.LinE2.RelationCatalogue
set_option maxRecDepth 100000
set_option maxHeartbeats 8000000
set_option Elab.async false

theorem archivedChunks_check : chunksCheck RawData.relationChunks.toList = true := by
  lin_homogeneous_compose {names}
end KIP126.LinE2.RelationCatalogue

namespace KIP126.LinE2
/-- Every relation in the unmodified archive is homogeneous for the original
bidegrees, with no bound or selected-relation hypothesis. -/
theorem csv_relation_isWeightedHomogeneous (code : String)
    (h : code ∈ RawData.relations) :
    ∃ d : ℕ × ℕ, MvPolynomial.IsWeightedHomogeneous generatorDegree (relationPolynomial code) d :=
  RelationCatalogue.allRelations_homogeneous_of_chunks
    (List.all_eq_true.mp RelationCatalogue.archivedChunks_check) code h
end KIP126.LinE2
'''
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    count = authenticate()
    outputs = render(count)
    for path, body in outputs.items():
        if args.check:
            if not path.is_file() or path.read_text() != body:
                raise SystemExit('generated homogeneity certificate differs: ' + str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(body)
    print(json.dumps(dict(relations=COUNT, archived_chunks=count, generated_modules=len(outputs), check=args.check)))


if __name__ == '__main__':
    main()
