#!/usr/bin/env python3
"""Export every row of the pinned S0 staircase, preserving SQL NULL.

This checks bytes, schema, coordinates, degree bounds, and decoder coverage.
It does not establish the mathematical truth of any decoded state.
"""
import argparse
from collections import Counter
import csv
import hashlib
import io
import json
from pathlib import Path
import re
import sqlite3

ROOT = Path(__file__).resolve().parents[3]
RAW = ROOT / "KIP126/LinProgram/Raw"
OUTPUT = ROOT / "KIP126/LinProgram/Generated/Staircase"
DB_HASH = "518a2ed86af6d4f7bcdc5db135ab6252bd50df34492ae208663aa1c140a820ed"
BASIS_HASH = "6a337964ad3ac02b729a46fd839dced7cb6764d14d4cea413163987eba8de871"
COLUMNS = ("id", "s", "t", "base", "diff", "level")
NAMESPACE = "KIP126.Computation.LinProofs.StaircaseData"
MODULE = "KIP126.LinProgram.Generated.Staircase"
SHARD_SIZE = 128


def checked_bytes(path, expected):
    value = path.read_bytes()
    if hashlib.sha256(value).hexdigest() != expected:
        raise ValueError(f"unreviewed source hash: {path}")
    return value


def coordinates(value):
    if value == "":
        return []
    if not isinstance(value, str) or not re.fullmatch(r"[0-9]+(,[0-9]+)*", value):
        raise ValueError(f"invalid coordinate vector: {value!r}")
    result = list(map(int, value.split(",")))
    if result != sorted(set(result)):
        raise ValueError(f"noncanonical coordinate vector: {value!r}")
    return result


def validate(row, basis):
    _, s, t, base, diff, level = row
    if not (isinstance(s, int) and isinstance(t, int) and 0 <= s and 0 <= t <= 261):
        raise ValueError(f"invalid degree: {row}")
    vectors = [(s, t, coordinates(base))]
    unknown = diff in (None, "-1", "[NULL]")
    if level == 9000:
        kind = "reaches-1000"
        if not unknown and diff != "":
            raise ValueError("unexpected nonzero threshold differential")
    elif 9000 < level <= 9998:
        r = 10000 - level
        kind = "reaches-finite" if unknown else "outgoing-equation"
        if not unknown:
            if t + r - 1 > 261:
                raise ValueError("target exceeds comparison range")
            vectors.append((s + r, t + r - 1, coordinates(diff)))
    elif 2 <= level < 999:
        kind = "boundary-bound" if unknown else "incoming-equation"
        if not unknown:
            if s < level or t < level - 1:
                raise ValueError("negative incoming source degree")
            vectors.append((s - level, t - level + 1, coordinates(diff)))
    else:
        raise ValueError(f"unsupported level: {row}")
    for vs, vt, indices in vectors:
        for index in indices:
            if (vs, vt, index) not in basis:
                raise ValueError(f"missing basis address {(vs, vt, index)}")
    return kind


def lean_option(value):
    if value is None:
        return "none"
    return "(some " + (json.dumps(value) if isinstance(value, str) else str(value)) + ")"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    database = RAW / "S0_AdamsSS_t261.db"
    checked_bytes(database, DB_HASH)
    basis_bytes = checked_bytes(RAW / "S0_AdamsE2_basis.csv", BASIS_HASH)
    basis = {(int(r["s"]), int(r["s"]) + int(r["stem"]), int(r["index"]))
             for r in csv.DictReader(io.StringIO(basis_bytes.decode("utf-16")))}
    with sqlite3.connect(database.as_uri() + "?mode=ro", uri=True) as con:
        if tuple(r[1] for r in con.execute("pragma table_info(S0_AdamsE2_ss)")) != COLUMNS:
            raise ValueError("unexpected staircase schema")
        rows = con.execute("select id,s,t,base,diff,level from S0_AdamsE2_ss order by id").fetchall()
    counts = Counter(validate(row, basis) for row in rows)
    files = {}
    count = (len(rows) + SHARD_SIZE - 1) // SHARD_SIZE
    for shard in range(count):
        block = rows[shard * SHARD_SIZE:(shard + 1) * SHARD_SIZE]
        literals = ["  ⟨" + str(r[0]) + ", " + ", ".join(map(lean_option, r[1:])) + "⟩" for r in block]
        files[f"Shard{shard:03}.lean"] = (
            "import KIP126.LinProgram.Raw.Staircase.Data\n\n"
            f"-- Generated by import-staircase.py; pinned database SHA-256: {DB_HASH}\n"
            f"namespace {NAMESPACE}\n\ndef shard{shard} : Array Raw.StaircaseRow := #[\n"
            + ",\n".join(literals) + f"\n]\n\nend {NAMESPACE}\n")
    files["Table.lean"] = (
        "\n".join(f"import {MODULE}.Shard{i:03}" for i in range(count))
        + f"\n\nnamespace {NAMESPACE}\n\ndef databaseSha256 : String := \"{DB_HASH}\"\n"
        + f"def sourceRowCount : Nat := {len(rows)}\n\ndef shardCount : Nat := {count}\n"
        + "\n/-- Lossless, shard-local lookup in the entire fixed sphere snapshot. -/\n"
        + "def lookup (shard offset : Nat) : Option Raw.StaircaseRow :=\n  match shard with\n"
        + "\n".join(f"  | {i} => shard{i}[offset]?" for i in range(count))
        + f"\n  | _ => none\n\nend {NAMESPACE}\n")
    files["manifest.json"] = json.dumps({
        "source": "https://zenodo.org/records/14875701", "version": "v126.3.cw49",
        "database": database.name, "database_sha256": DB_HASH,
        "table": "S0_AdamsE2_ss", "basis_sha256": BASIS_HASH,
        "row_count": len(rows), "shard_size": SHARD_SIZE, "shard_count": count,
        "decoded_kinds": dict(sorted(counts.items())),
        "scope": "All raw sphere snapshot rows, retaining NULL; mathematical soundness unproved."
    }, indent=2) + "\n"
    if not args.check:
        OUTPUT.mkdir(parents=True, exist_ok=True)
    for name, content in files.items():
        path = OUTPUT / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise ValueError(f"generated output mismatch: {path}")
        else:
            path.write_text(content)
    print(f"PASS: {len(rows)} lossless rows, {count} shards; {dict(counts)}")


if __name__ == "__main__":
    main()
